export type TextVars = Record<string, string | number>;
/** Looks up a website text: `t("compare.heading")`, `t("blog.minRead", { minutes: 5 })`. */
export type T = (key: string, vars?: TextVars) => string;

/** Replaces `{name}` placeholders; unknown ones are left as they are. */
export function fillText(template: string, vars?: TextVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Builds the lookup from the saved changes (`settings.texts`): a saved text wins over the default, even when empty. */
export function makeT(overrides?: Record<string, string> | null): T {
  const o = overrides ?? {};
  return (key, vars) => fillText(Object.prototype.hasOwnProperty.call(o, key) ? (o[key] as string) : (TEXT_DEFAULTS[key] ?? key), vars);
}
