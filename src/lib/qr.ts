/**
 * Minimal QR Code encoder (ISO/IEC 18004, byte mode, versions 1–40) with no dependencies.
 * Used to render otpauth:// links for authenticator apps. Works on server and client.
 */

export type QrLevel = "L" | "M" | "Q" | "H";

const LEVEL_INDEX: Record<QrLevel, number> = { L: 0, M: 1, Q: 2, H: 3 };
const FORMAT_BITS: Record<QrLevel, number> = { L: 1, M: 0, Q: 3, H: 2 };

